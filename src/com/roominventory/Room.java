package com.roominventory;

public class Room {
		int count;
		double price;
		
		public Room(int count, double price) {
			this.count = count;
			this.price = price;
		}

		public int getCount() {
			return count;
		}

		public void setCount(int count) {
			this.count = count;
		}

		public double getPrice() {
			return price;
		}

		public void setPrice(double price) {
			this.price = price;
		}
		
		
}
